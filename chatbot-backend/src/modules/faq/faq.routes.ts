import { Router } from 'express';
import { checkSitePermission, requireAdmin, verifyToken } from '../../middlewares/auth.middleware';
import faqImagesRoutes from '../faq/faq-images.route';
import { deleteFaqBatch, getFaqBatches, reviewFaqBatch, syncFaqDatabase } from './faq-batch.controller';
import { backfillFaqEmbeddings } from './faq-embedding';
import { createFaqItem, deleteFaqMasterItem, getFaqMasterById, getFaqMasterList, reviewFaqItem, updateFaqItem } from './faq-item.controller';
const router = Router();
router.post('/sync', verifyToken, checkSitePermission, syncFaqDatabase);
router.get('/batches', verifyToken, checkSitePermission, getFaqBatches);
router.delete('/batches/:id', verifyToken, deleteFaqBatch);
router.post('/batches/:id/review', verifyToken, requireAdmin, reviewFaqBatch);
router.get('/', verifyToken, checkSitePermission, getFaqMasterList);
router.get('/:id', verifyToken, getFaqMasterById);
router.post('/', verifyToken, checkSitePermission, createFaqItem);
router.put('/:id', verifyToken, updateFaqItem);
router.post('/:id/review', verifyToken, requireAdmin, reviewFaqItem);
router.delete('/:id', verifyToken, deleteFaqMasterItem);
router.use('/:id/images', faqImagesRoutes);
router.post('/backfill-embeddings', verifyToken, requireAdmin, backfillFaqEmbeddings);
export default router;
